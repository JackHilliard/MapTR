#
# MapTRv2 LiDAR-only config (CARLA) -- 30m x 30m tiles (tile_radius=15).
#
# Sibling of maptrv2_carla_r50_24ep_lidar.py, which targets the original
# 25m x 25m export (tile_radius=12.5). Everything that is NOT tile-size
# dependent is deliberately identical to that file, so a diff between the
# two shows exactly what tile size costs. The tile-size dependent knobs are
# marked "[30m]" below; there are seven of them, and one (data.*.pc_range)
# is NOT overridden by the 25m config and therefore easy to miss -- see the
# note on it further down.
#
# Project-wide conventions (2026-08-27, see CLAUDE.md): the GT frame is
# `tile_center` (the converter's default --gt-frame; loader recenter=True
# below) and the point cloud is COLOUR-FREE (use_dim=3 on the loaders,
# in_channels=3 on the SparseEncoder -- the two must move together). The
# former offset-frame / colour-carrying variants are gone; checkpoints
# trained under them are not comparable with this config.
#
# The tile-centre frame matters MORE at 30 m than at 25 m: the square
# lidar_point_cloud_range is centred on the origin, so in the offset frame
# it sits off the actual tile and crops it -- on `../carla_test`
# (|offset - tile_center| up to 117 m) the offset frame drops 75 tiles
# outright and leaves 1282 more under 90% point coverage, vs 0 dropped and
# median 100% coverage recentred.
#
# Requires a 30m pkl generated by the (tile-size agnostic) converter:
#   python tools/maptrv2/custom_carla_map_converter.py \
#       --data-root <30m export> --split test \
#       --out-dir data/carla/ --out-tag 30m_tc
# The converter derives --lidar-point-cloud-range from the manifest's own
# tile_radius/tile_side, so it will pick +-15 by itself; the range recorded
# in the pkl must match lidar_point_cloud_range below or the dataset warns.
# Check its `_dropped.json` before training -- a large drop count means the
# range is wrong, not that the data is bad.
#
