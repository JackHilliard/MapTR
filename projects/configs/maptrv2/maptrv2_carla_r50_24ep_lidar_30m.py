# but never reaches the final regression target), and this just needs to
# comfortably contain the LiDAR point cloud's z spread. z is unchanged from
# the 25m config -- tile size is an XY property.
point_cloud_range = [-15.0, -15.0, -30.0, 15.0, 15.0, 20.0]
# Deliberately NOT scaled with tile size: MapTRNMSFreeCoder stores
