# confirmed town03 tiles whose LiDAR returns span z in [-66.90, 90.52]
# within a single tile (a highway overpass, not flat driving surface). See
# the 25m config for the full history. z_max in carlasim_map.py
# (LoadCarlaPointsFromFile's early filter) must stay >= this range's z upper
# bound.
#
# NOTE (CLAUDE.md open item): 98 tiles in the 25m train set have z_min below
